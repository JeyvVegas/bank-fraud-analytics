-- 01_data_profile.sql
-- Профиль датасета Fraud.csv — стартовый анализ перед импортом
-- Источник: Kaggle (PaySim — симуляция банковских транзакций)
-- ============================================================

-- Файл: Fraud.csv
-- Размер: 493.53 MB (493,534,783 байт)
-- Строк: 6 362 620
-- Полей: 11
-- Примечание: в описании на Kaggle указано "10 columns" — это
-- неточность автора, фактических полей 11.

-- ------------------------------------------------------------
-- ОПИСАНИЕ ПОЛЕЙ
-- ------------------------------------------------------------
-- step             — час симуляции (1 шаг = 1 час, всего 743–744 шага)
-- type             — тип операции: CASH_IN, CASH_OUT, DEBIT, PAYMENT, TRANSFER
-- amount           — сумма операции
-- nameOrig         — идентификатор отправителя (префикс C — клиент)
-- oldbalanceOrg    — баланс отправителя до операции
-- newbalanceOrig   — баланс отправителя после операции
-- nameDest         — идентификатор получателя (C — клиент, M — мерчант)
-- oldbalanceDest   — баланс получателя до операции
-- newbalanceDest   — баланс получателя после операции
-- isFraud          — целевой признак: 1 = мошенническая операция, 0 = обычная
-- isFlaggedFraud   — срабатывание антифрод-правила банка (переводы > 200 000)

-- ------------------------------------------------------------
-- РЕЗУЛЬТАТЫ ПРОВЕРОК КАЧЕСТВА
-- ------------------------------------------------------------
-- Пропусков: 0 во всех 11 полях
-- Полных дубликатов строк: 0
-- Структурно повреждённых строк: 0
-- Некорректных числовых / бинарных значений: 0
-- Отрицательных сумм: 0
-- Диапазон amount: от 0 до 92 445 516.64
-- Средняя сумма операции: 179 861.90

-- ------------------------------------------------------------
-- РАСПРЕДЕЛЕНИЕ ПО ТИПАМ ОПЕРАЦИЙ
-- ------------------------------------------------------------
-- CASH_OUT   2 237 500
-- PAYMENT    2 151 495
-- CASH_IN    1 399 284
-- TRANSFER     532 909
-- DEBIT         41 432

-- ------------------------------------------------------------
-- ЦЕЛЕВОЙ ПРИЗНАК (isFraud)
-- ------------------------------------------------------------
-- Fraud-операций: 8 213 (≈ 0.129% всех транзакций)
-- Fraud встречается ТОЛЬКО в типах:
--   TRANSFER  — 4 097
--   CASH_OUT  — 4 116
-- В PAYMENT, DEBIT, CASH_IN fraud не обнаружен.

-- ------------------------------------------------------------
-- ТЕКУЩЕЕ АНТИФРОД-ПРАВИЛО (isFlaggedFraud)
-- ------------------------------------------------------------
-- Сработало 16 раз из 6 362 620 операций
-- Все 16 — TRANSFER, все действительно fraud
-- Все 16 — суммы > 200 000
-- Покрытие: 16 из 8 213 fraud-операций (0.39%)
-- Правило очень узкое — это не полноценная антифрод-модель,
-- а базовый контроль крупных переводов.

-- ------------------------------------------------------------
-- АНОМАЛИИ И ОГРАНИЧЕНИЯ ДАННЫХ
-- ------------------------------------------------------------
-- 1. 16 операций CASH_OUT с суммой 0 — требуют отдельного рассмотрения.
-- 2. У 3 601 562 исходящих операций (72.6%) новый баланс отправителя
--    не равен oldbalanceOrg − amount. Балансы не сходятся.
-- 3. Для CASH_IN формула oldbalanceOrg + amount нарушена только
--    в 33 строках из 1 399 284.
-- 4. У 269 723 из 2 770 409 переводов/снятий баланс получателя
--    не меняется на сумму операции.
-- 5. Все PAYMENT идут на получателя с префиксом M (merchant),
--    у которого баланс до и после = 0. По дизайну датасета информация
--    по merchant-клиентам не детализируется.

-- ------------------------------------------------------------
-- ГЛАВНЫЙ ВЫВОД
-- ------------------------------------------------------------
-- Датасет полностью пригоден для fraud-анализа:
--   - большой объём (6.36 млн операций),
--   - структурно чистый (нет пропусков и дубликатов),
--   - реалистично редкий fraud-класс (0.129%).
--
-- ВАЖНО: балансные поля нельзя использовать как бухгалтерскую истину.
-- Это часть data-quality story проекта: сначала показываем ограничения
-- данных, затем не строим выводы о fraud только на балансах.